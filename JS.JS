// --- Language Switcher Function ---
function changeLanguage(lang) {
  document.documentElement.lang = lang;

  const btnEn = document.getElementById("btn-en");
  const btnFr = document.getElementById("btn-fr");

  if (btnEn && btnFr) {
    if (lang === 'en') {
      btnEn.classList.add("active");
      btnFr.classList.remove("active");
    } else {
      btnFr.classList.add("active");
      btnEn.classList.remove("active");
    }
  }

  const elements = document.querySelectorAll("[data-i18n]");
  elements.forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang] && translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });
}

// Ensure event listeners bind cleanly after DOM content loads
document.addEventListener("DOMContentLoaded", () => {
  const btnEn = document.getElementById("btn-en");
  const btnFr = document.getElementById("btn-fr");

  if (btnEn) btnEn.addEventListener("click", () => changeLanguage('en'));
  if (btnFr) btnFr.addEventListener("click", () => changeLanguage('fr'));
});

// --- Navbar Scroll Effect ---
const nav = document.querySelector(".navbar");
const navTogglerIcon = document.querySelector(".navbar-toggler-icon-custom");

window.addEventListener("scroll", () => {
  if (window.scrollY > 50) {
    nav.classList.add("scrolled");
    if (navTogglerIcon) navTogglerIcon.classList.replace("text-white", "text-dark");
  } else {
    nav.classList.remove("scrolled");
    if (navTogglerIcon) navTogglerIcon.classList.replace("text-dark", "text-white");
  }
});

// --- Fade-up Section Animations ---
const sections = document.querySelectorAll(".animate-section");

const observer = new IntersectionObserver((entries) => {
  entries.forEach(entry => {
    const items = entry.target.querySelectorAll(".fade-up");

    if (entry.isIntersecting) {
      items.forEach((item, index) => {
        setTimeout(() => {
          item.classList.add("show");
        }, index * 100);
      });
    } else {
      items.forEach(item => {
        item.classList.remove("show");
      });
    }
  });
}, {
  threshold: 0.1
});

sections.forEach(section => observer.observe(section));
